export function getTemplateCsv(moduleName: ImportModule): string {
  const headers = TEMPLATE_HEADERS[moduleName]
  const sample = TEMPLATE_SAMPLE_ROW[moduleName]
  const lines = [headers.join(","), sample.join(",")]
  return lines.join("\n")
}

export function isImportModule(value: string): value is ImportModule {
  return IMPORT_MODULES.includes(value as ImportModule)
}

